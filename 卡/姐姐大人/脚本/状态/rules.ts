// 今天轮到他主动发一则小红书；发过了（记发文）就不再提醒。内容只给方向，跟着当下的状态走
function 发文文(stat: Stat): string | null {
  const 日 = stat._状态?.日常;
  if (!今天的日常(stat) || !日?.发文 || 日.已发) return null;
  const 穷 = 日.发文 === '穷云海';
  const 大事 = 今天的日常(stat)?.大事;
  const 方向: string[] = 穷
    ? [
        '穷云海的账号：照片不露脸，拍布料、手、背影或一角静物；配一句短短的话，安静，有一点诗意。',
        '绝不透露真实身分、住址、工作，也不暗示他是男性。',
      ]
    : [
        '黎靖青本人的账号：几乎没人关注，他也很少发。一张他生活里的照片，话很少，可能只有几个字，甚至不写。',
        '和穷云海的账号风格完全不同，看不出是同一个人。',
      ];
  if (大事) 方向.push('可以和今天的事有关，但不写明发生了什么。');
  if (穷 && 阶段到(线上阶段, stat.关系?.线上, '熟网友') && stat['黎靖青/穷云海']?.认出聊天对象 !== '认出') {
    方向.push('偶尔，这一则可能是只有网友「{网名}」才看得懂的东西。');
  }
  if (两头心动(stat)) 方向.push('字里行间带一点说不清的犹豫，不说破。');
  return [
    '<今天的动态>',
    `今天${日.发文}会主动发一则小红书。在今天合适的一回合，于正文末尾用小红书格式发出（发布者写「${日.发文}」），时间配合剧情；发过就不要再发。`,
    ...方向,
    '封面字和标题都很短、很淡，不要用〈手机-格式〉说的「突出震撼效果」那种写法。附 3～5 条路人评论（评论人 momo），他可能回其中一条。',
    '</今天的动态>',
  ].join('\n');
}

function 试探余波(stat: Stat): string | null {
  const 试 = stat._状态?.身分试探 ?? {};
  if (试.进行中) return null;
  if (试.结果 === '接受') {
    return '身分试探已经结束：他得到了想要的答案——{{user}}接受完整的他。内心的不安缓解了，能更自信地与{{user}}相处。';
  }
  if (试.结果 === '抗拒') {
    return '上一次身分试探时，{{user}}没有接受他。他把自己收了回去，比之前更谨慎，却没有真的放弃。';
  }
  if (试.结果 === '回避') {
    return '上一次身分试探时，{{user}}回避了。他把问题收了回去，装作没问过，心里却一直记着。';
  }
  return null;
}

export function 底色文(stat: Stat, 网名: string): string {
  const 人 = stat.黎靖青 ?? {};
  const 身份 = 人.目前身份 === '穷云海' ? '穷云海' : '黎靖青';
  const 场合 = 规范场合(身份, 人.场合);
  const 冷 = num(人.冷淡值);
  const 亲 = num(人.亲密值);
  const 兴 = num(人.兴奋值);

  const 段: string[] = [
    '<黎靖青当前状态>',
    '黎靖青与穷云海是同一个人，共享全部记忆与认知；穷云海不是第二人格。以下是此刻的状态，不是每回合要演的清单，挑与当下相关的自然带出即可。',
    '',
    身份场合文[`${身份}/${场合}`],
    '',
    '【认知】',
    认知文(stat),
    '',
    '【关系】',
    现实关系文[stat.关系?.现实] ?? 现实关系文.同事,
  ];
  if (!已全部揭穿(stat)) 段.push(线上关系文[stat.关系?.线上] ?? 线上关系文.无);
  段.push(账号文);

  const 今天 = 小事文(stat);
  if (今天) 段.push('', '【今天】', 今天);

  段.push('', ...心态文(身份, 亲, 冷, 兴));
  if (身份 === '穷云海') 段.push('营业时，这份心思只从细节泄露。');
  if (亲 > 50) {
    段.push(
      '亲近到这个程度，黎靖青会要求{{user}}叫他哥哥（就算{{user}}年纪比他大；偶尔也能接受被叫弟弟），私下床事时是主人。',
    );
  }

  for (const 情境 of [两头心动(stat), 松下来(场合, 亲, 冷), 玩心(亲, 冷, 兴)]) if (情境) 段.push('', 情境);

  const 余波 = 试探余波(stat);
  if (余波) 段.push('', 余波);

  段.push('</黎靖青当前状态>');
  return 段.join('\n').replaceAll('{网名}', 网名);
}

