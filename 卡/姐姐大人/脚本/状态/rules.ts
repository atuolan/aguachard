function 是周末(时间点: unknown): boolean {
  return /星期[六日天]|周[六日天]/.test(String(时间点 ?? ''));
}

// 換日才擲；開場那天（還沒有日期）只記日期不擲，免得和開場白寫好的行程打架
function 日常结算(stat: Stat, 今天: string, 随机: () => number, log: string[]): void {
  const 日 = _.get(stat, '_状态.日常') ?? {};
  _.set(stat, '_状态.日常', 日);
  if (!今天 || 日.日期 === 今天) return;
  const 第一天 = !日.日期;
  日.日期 = 今天;
  日.小事 = '';
  日.大事 = '';
  if (第一天) return;

  const 周末 = 是周末(stat.世界?.时间点);
  const r = 随机();
  日.小事 = 周末
    ? r < 日常.排班
      ? '有排班'
      : '没排班'
    : r < 日常.准时
      ? '准时下班'
      : r < 日常.准时 + 日常.早下班
        ? '早下班'
        : '加班';

  抽大事(日, 周末, 随机);
  抽发文(日, 随机);
  log.push(`日常 ${今天}：${[日.小事, 日.大事 && `大事「${日.大事}」`, 日.发文 && `${日.发文}发文`].filter(Boolean).join('，')}`);
}

function 抽大事(日: Stat, 周末: boolean, 随机: () => number): void {
  日.距上次大事 = num(日.距上次大事 ?? 99) + 1;
  if (日.距上次大事 < 日常.大事间隔 || 随机() >= 日常.大事机率) return;
  const 池们: 池[] = 周末
    ? 日.小事 === '有排班'
      ? ['咖啡厅', '家']
      : ['家']
    : 日.小事 === '早下班'
      ? ['家']
      : ['公司', '家'];
  const 袋 = (日.袋 ??= {});
  const 候选: string[] = [];
  for (const p of 池们) {
    if (!袋[p]?.length) 袋[p] = 日常事件表.filter(e => e.池 === p).map(e => e.名);
    候选.push(...袋[p]);
  }
  const 名 = 候选[Math.floor(随机() * 候选.length)];
  const 事 = 日常事件表.find(e => e.名 === 名)!;
  袋[事.池] = 袋[事.池].filter((n: string) => n !== 名);
  日.大事 = 名;
  日.距上次大事 = 0;
}

function 抽发文(日: Stat, 随机: () => number): void {
  日.发文 = '';
  日.已发 = false;
  日.距上次发文 = num(日.距上次发文 ?? 99) + 1;
  if (日.距上次发文 < 日常.发文间隔 || 随机() >= 日常.发文机率) return;
  日.发文 = 随机() < 日常.黎靖青发文 ? '黎靖青' : '穷云海';
  日.距上次发文 = 0;
}

// 正文里出现他发的小红书帖子（9 栏的 <rednote>，发布者是穷云海或黎靖青），今天就算发过了
const 他的帖子 = /<rednote>\s*[^|<]*\|\s*(穷云海|黎靖青)\s*\|(?:[^|<]*\|){6}[^|<]*<\/rednote>/;
function 记发文(stat: Stat, 本楼文本: string, log: string[]): void {
  const 日 = stat._状态?.日常;
  if (!日?.发文 || 日.已发 || !他的帖子.test(本楼文本)) return;
  日.已发 = true;
  log.push(`${日.发文}今天的动态已发`);
}

function num(v: unknown): number {
  return typeof v === 'number' ? v : Number(v);
}

function 日期(时间点: unknown): string {
  return String(时间点 ?? '').match(/^(\d{2}月\d{2}日)/)?.[1] ?? '';
}

// 黎靖青不會在營業，穷云海不會在職場；模型換了身分卻忘了改場合時，退回「私下」
export function 规范场合(身份: unknown, 场合: unknown): string {
  if (身份 === '穷云海') return 场合 === '营业' ? '营业' : '私下';
  return 场合 === '职场' ? '职场' : '私下';
}

export function 已全部揭穿(stat: Stat): boolean {
  return stat.user?.识破身份 === '识破' && stat['黎靖青/穷云海']?.认出聊天对象 === '认出';
}

function 一次一段(阶段: string[], 旧: unknown, 新: unknown): string | null {
  const a = 阶段.indexOf(String(旧));
  const b = 阶段.indexOf(String(新));
  if (a < 0 || b < 0 || Math.abs(b - a) <= 1) return null;
  return 阶段[a + Math.sign(b - a)];
}

function 套用变化(人: Stat, 变化: Record<string, number>): void {
  for (const [k, d] of Object.entries(变化)) 人[k] = _.clamp(num(人[k]) + d, 0, 100);
}

// ===== 結算 =====
// stat 會被直接改寫；prev 是這次更新前的 stat_data（第 0 樓的開場白沒有 prev）。
// AI楼：這次更新的是 AI 回覆（MVU 對使用者樓也會發更新事件，那種不算試探進度）。
export function 结算(
  stat: Stat,
  prev: Stat | null,
  AI楼: boolean,
  随机: () => number = Math.random,
  本楼文本 = '',
): string[] {
  const log: string[] = [];
  const 人 = stat.黎靖青;
  if (!人) return log;
  const 状态 = (stat._状态 ??= {});
  const 每日 = (状态.每日 ??= {});
  const 试 = (状态.身分试探 ??= {});

  const 场合 = 规范场合(人.目前身份, 人.场合);
  if (场合 !== 人.场合) {
    log.push(`场合「${人.场合}」不合身分「${人.目前身份}」，改为「${场合}」`);
    人.场合 = 场合;
  }

  // 第 0 樓：開場白在設定起點，寫的是絕對值，不套上限與鎖定
  const 旧人 = prev?.黎靖青;
  if (prev && 旧人) {
    // 不可逆
    if (prev.user?.识破身份 === '识破' && stat.user?.识破身份 !== '识破') {
      _.set(stat, 'user.识破身份', '识破');
      log.push('识破身份不可逆，已挡回');
    }
    if (prev['黎靖青/穷云海']?.认出聊天对象 === '认出' && stat['黎靖青/穷云海']?.认出聊天对象 !== '认出') {
      _.set(stat, ['黎靖青/穷云海', '认出聊天对象'], '认出');
      log.push('认出聊天对象不可逆，已挡回');
    }

    // 關係一次只升降一段
    for (const [线, 阶段] of [
      ['现实', 现实阶段],
      ['线上', 线上阶段],
    ] as const) {
      const 修正 = 一次一段(阶段, prev.关系?.[线], stat.关系?.[线]);
      if (修正) {
        log.push(`关系.${线} ${prev.关系?.[线]} → ${stat.关系?.[线]} 跳太多，改为 ${修正}`);
        _.set(stat, ['关系', 线], 修正);
      }
    }

    // 數值：鎖定 → 單次上限 → 每日累計
    const 锁定原因 = 人.性爱场景中 === true ? '性爱场景中' : 试.进行中 === true ? '身分试探中' : '';
    const 今天 = 日期(stat.世界?.时间点);
    if (每日.日期 !== 今天) {
      每日.日期 = 今天;
      for (const k of 每日属性) 每日[k] = { 累计: 0, 锁定: false };
    }
    for (const k of ['冷淡值', '亲密值', '兴奋值']) {
      const 旧 = num(旧人[k]);
      let 新 = num(人[k]);
      if (!Number.isFinite(旧)) continue;
      if (!Number.isFinite(新)) 新 = 旧;
      if (锁定原因 && k !== '兴奋值') {
        if (新 !== 旧) log.push(`${k} ${锁定原因}锁定，${新} 退回 ${旧}`);
        人[k] = 旧;
        continue;
      }
      const 上限 = 人.目前身份 === '穷云海' && k in 穷云海上限 ? 穷云海上限[k] : 单次上限[k];
      const 修正 = 旧 + _.clamp(新 - 旧, -上限, 上限);
      if (修正 !== 新) log.push(`${k} 单次变动 ${新 - 旧} 超过 ±${上限}，改为 ${修正 - 旧}`);
      人[k] = 修正;

      if (!(每日属性 as readonly string[]).includes(k) || 修正 === 旧) continue;
      const 额 = (每日[k] ??= { 累计: 0, 锁定: false });
      if (额.锁定) {
        人[k] = 旧;
        log.push(`${k} 今日变动已满，退回 ${旧}`);
        continue;
      }
      额.累计 = num(额.累计 || 0) + Math.abs(修正 - 旧);
      if (额.累计 >= 每日上限) {
        额.锁定 = true;
        log.push(`${k} 今日累计 ${额.累计}，锁定到明天`);
      }
    }
  }

  // 身分試探
  const 场景 = (stat.场景 ??= {});
  if (prev && 旧人) {
    if (AI楼 && !试.进行中 && num(试.冷却) > 0) 试.冷却 = num(试.冷却) - 1;
    if (试.进行中) {
      if (AI楼) 试.进度 = num(试.进度 || 0) + 1;
      const 回报 = Boolean(场景.事件完成 || 场景.表态);
      const 结果 =
        num(试.进度) >= 试探.摊牌 && 回报 ? 场景.表态 || '回避' : num(试.进度) >= 试探.自动回避 ? '回避' : '';
      if (结果 === '接受') {
        Object.assign(试, { 进行中: false, 已完成: true, 结果 });
        套用变化(人, 试探.接受);
        log.push('身分试探收尾：接受');
      } else if (结果) {
        Object.assign(试, { 进行中: false, 进度: 0, 结果, 冷却: 试探.冷却 });
        套用变化(人, 试探.拒绝);
        log.push(`身分试探收尾：${结果}${回报 ? '' : '（摊牌后一直没有表态，当作回避）'}`);
      }
    } else if (!试.已完成 && num(试.冷却 || 0) <= 0 && 试探.触发(num(人.亲密值), num(人.冷淡值))) {
      Object.assign(试, { 进行中: true, 进度: 0, 结果: '' });
      log.push('身分试探开始');
    }
  }
  场景.事件完成 = '';
  场景.表态 = '';

  if (prev && 旧人) {
    日常结算(stat, 日期(stat.世界?.时间点), 随机, log);
    记发文(stat, 本楼文本, log);
  }

  return log;
}

